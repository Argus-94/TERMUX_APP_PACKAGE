const tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'aib-terminal-private-layout-'));
try {
  const files = path.join(tempRoot, 'files');
  const foreign = path.join(tempRoot, 'foreign');
  fs.mkdirSync(path.join(files, 'usr'), { recursive: true });
  fs.mkdirSync(path.join(files, 'home'), { recursive: true });
  fs.mkdirSync(foreign);
  const canonicalChildMatches = name => fs.realpathSync(path.join(files, name)) === path.resolve(files, name);
  assert.equal(canonicalChildMatches('usr'), true);
  assert.equal(canonicalChildMatches('home'), true);
  fs.rmSync(path.join(files, 'usr'), { recursive: true, force: true });
  fs.symlinkSync(foreign, path.join(files, 'usr'), 'dir');
  assert.equal(canonicalChildMatches('usr'), false, 'usr symlink outside private files root is rejected');
  fs.rmSync(path.join(files, 'usr'), { recursive: true, force: true });
  fs.mkdirSync(path.join(files, 'usr'));
  fs.rmSync(path.join(files, 'home'), { recursive: true, force: true });
  fs.symlinkSync(foreign, path.join(files, 'home'), 'dir');
  assert.equal(canonicalChildMatches('home'), false, 'home symlink outside private files root is rejected');
} finally { fs.rmSync(tempRoot, { recursive: true, force: true }); }
