import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const root = path.resolve(new URL('..', import.meta.url).pathname);
const verifier = path.join(root, 'scripts/aib-verify-custom-termux-bootstrap.mjs');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'aib-bootstrap-verify-'));
const run = (args) => spawnSync(process.execPath, [verifier, ...args], { encoding: 'utf8' });
try {
  const staging = path.join(temp, 'stage');
  fs.mkdirSync(path.join(staging, 'bin'), { recursive: true });
  fs.writeFileSync(path.join(staging, 'bin/bash'), '#!/data/data/com.karat.aibuilder/files/usr/bin/sh\nexit 0\n');
  fs.writeFileSync(path.join(staging, 'bin/termux-exec-ld-preload-lib'), '#!/bin/sh\n# Upstream diagnostic example: /data/data/com.termux/files/usr/lib/example.so\nexit 0\n');
  const archive = path.join(temp, 'termux-bootstrap-aarch64.zip');
  const zip = spawnSync('zip', ['-qr', archive, '.'], { cwd: staging, encoding: 'utf8' });
  assert.equal(zip.status, 0, zip.stderr);
  const sha = spawnSync('sha256sum', [archive], { encoding: 'utf8' }).stdout.split(/\s+/)[0];
  fs.writeFileSync(`${archive}.sha256`, `${sha}  ${path.basename(archive)}\n`);
  fs.writeFileSync(`${archive}.provenance.json`, JSON.stringify({ schemaVersion: 1, applicationId: 'com.karat.aibuilder', architecture: 'aarch64', archiveFile: path.basename(archive), archiveSha256: sha, sourceRepository: '/tmp/termux-packages', sourceBranch: 'main', sourceCommit: 'abcdef0123456789', builtAtUtc: '2026-10-12T00:00:00Z', archiveStructureVerified: true, runtimeVerified: false, apkIntegrated: false }));
  const good = run([archive, 'aarch64']);
  assert.equal(good.status, 0, `${good.stdout}\n${good.stderr}`);
  const foreignStage = path.join(temp, 'foreign-stage');
  fs.mkdirSync(path.join(foreignStage, 'bin'), { recursive: true });
  fs.writeFileSync(path.join(foreignStage, 'bin/bash'), '#!/bin/sh\nexit 0\n');
  fs.writeFileSync(path.join(foreignStage, 'bin/pkg'), '#!/bin/sh\nPREFIX=/data/data/com.termux/files/usr\n');
  const foreignArchive = path.join(temp, 'foreign-bootstrap.zip');
  const foreignZip = spawnSync('zip', ['-qr', foreignArchive, '.'], { cwd: foreignStage, encoding: 'utf8' });
  assert.equal(foreignZip.status, 0, foreignZip.stderr);
  const foreignSha = spawnSync('sha256sum', [foreignArchive], { encoding: 'utf8' }).stdout.split(/\s+/)[0];
  fs.writeFileSync(`${foreignArchive}.sha256`, `${foreignSha}  ${path.basename(foreignArchive)}\n`);
  const baseManifest = JSON.parse(fs.readFileSync(`${archive}.provenance.json`, 'utf8'));
  fs.writeFileSync(`${foreignArchive}.provenance.json`, JSON.stringify({ ...baseManifest, archiveFile: path.basename(foreignArchive), archiveSha256: foreignSha }));
  const foreign = run([foreignArchive, 'aarch64']);
  assert.equal(foreign.status, 2);
  assert.match(foreign.stderr, /foreign Android app path.*com\.termux/);
  const nestedStage = path.join(temp, 'nested-stage');
  fs.mkdirSync(path.join(nestedStage, 'usr/bin'), { recursive: true });
  fs.writeFileSync(path.join(nestedStage, 'usr/bin/bash'), '#!/bin/sh\nexit 0\n');
  const nestedArchive = path.join(temp, 'nested-bootstrap.zip');
  const nestedZip = spawnSync('zip', ['-qr', nestedArchive, '.'], { cwd: nestedStage, encoding: 'utf8' });
  assert.equal(nestedZip.status, 0, nestedZip.stderr);
  const nestedSha = spawnSync('sha256sum', [nestedArchive], { encoding: 'utf8' }).stdout.split(/\s+/)[0];
  fs.writeFileSync(`${nestedArchive}.sha256`, `${nestedSha}  ${path.basename(nestedArchive)}\n`);
  const nestedManifest = { ...JSON.parse(fs.readFileSync(`${archive}.provenance.json`, 'utf8')), archiveFile: path.basename(nestedArchive), archiveSha256: nestedSha };
  fs.writeFileSync(`${nestedArchive}.provenance.json`, JSON.stringify(nestedManifest));
  const nested = run([nestedArchive, 'aarch64']);
  assert.equal(nested.status, 2);
  assert.match(nested.stderr, /prefix-root bin\/bash/);
  const wrongArch = run([archive, 'x86_64']);
  assert.equal(wrongArch.status, 2);
  assert.match(wrongArch.stderr, /Architecture mismatch/);
  const validManifest = JSON.parse(fs.readFileSync(`${archive}.provenance.json`, 'utf8'));
  delete validManifest.sourceCommit;
  fs.writeFileSync(`${archive}.provenance.json`, JSON.stringify(validManifest));
  const missingProvenance = run([archive, 'aarch64']);
  assert.equal(missingProvenance.status, 2);
  assert.match(missingProvenance.stderr, /sourceCommit is missing/);
  validManifest.sourceCommit = 'abcdef0123456789';
  fs.writeFileSync(`${archive}.provenance.json`, JSON.stringify(validManifest));
  fs.writeFileSync(`${archive}.sha256`, `${'0'.repeat(64)}  ${path.basename(archive)}\n`);
  const badHash = run([archive, 'aarch64']);
  assert.equal(badHash.status, 2);
  assert.match(badHash.stderr, /SHA-256 sidecar does not match/);
  console.log('PASS: artifact verifier enforces app-specific runtime paths and rejects nested usr/, foreign namespaces, ABI and hash mismatches');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
